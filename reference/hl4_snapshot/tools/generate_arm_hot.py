"""Specialize the local pure ARM decoder for measured HL4 regions, not HL5 hooks."""
import argparse,hashlib,io,json,struct,sys,zipfile
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(ROOT/'scratch/analysis_deps'))
from elftools.elf.elffile import ELFFile
from capstone import Cs,CS_ARCH_ARM,CS_MODE_ARM
from arm_emit import emit
REGIONS=[[(0x505d8,0x50620)],[(0x49eac,0x49fbc),(0x49ffc,0x4a040)],
 [(0x4a4f0,0x4a72c),(0x4a738,0x4a77c)],
 [(0x3fdec,0x44ddc)],[(0x3de54,0x3f878)],
 [(0x52ab4,0x52b00)],[(0x24d8c,0x24f68)],
 [(0xc901c,0xc9288)],[(0x4a7c4,0x4ab0c)],[(0x524c0,0x52628)]]
WHOLE={3,4,7,8,9} # Follow the original CFG; literal pools and POP-PC stay interpreted.
def generate():
 cfg=json.loads((ROOT/'project.json').read_text(encoding='utf8'))
 apk=(ROOT/cfg['original_apk']['path']).read_bytes();assert hashlib.sha256(apk).hexdigest()==cfg['original_apk']['sha256']
 with zipfile.ZipFile(io.BytesIO(apk)) as z:blob=z.read('lib/armeabi/libbinary.so')
 elf=ELFFile(io.BytesIO(blob));md=Cs(CS_ARCH_ARM,CS_MODE_ARM);ops={};regions=[]
 def opcode(pc):
  seg=next(s for s in elf.iter_segments() if s['p_type']=='PT_LOAD' and s['p_vaddr']<=pc and pc+4<=s['p_vaddr']+s['p_filesz'])
  off=pc-seg['p_vaddr']+seg['p_offset'];return struct.unpack_from('<I',blob,off)[0],blob[off:off+4]
 def branch_target(pc,ins):
  off=(ins&0xffffff)*4
  if off&(1<<25):off-=1<<26
  return pc+8+off
 for index,ranges in enumerate(REGIONS):
  if index in WHOLE:
   lo,hi=ranges[0];pending=[lo];visited=set();included=set()
   while pending:
    pc=pending.pop()
    if pc in visited or not lo<=pc<=hi:continue
    visited.add(pc);ins,raw=opcode(pc)
    # Do not execute the epilogue in native code: Unicorn restores SP/PC and
    # handles any interworking semantics. All incoming edges exit here.
    if ((ins>>25)&7)==4 and ins&(1<<20) and ins&(1<<15):continue
    included.add(pc)
    if ((ins>>25)&7)==5:
     assert not ins&(1<<24),'Unexpected call in whole graphics CFG'
     pending.append(branch_target(pc,ins))
     if ins>>28!=14:pending.append(pc+4)
    else:pending.append(pc+4)
   ranges=[]
   for pc in sorted(included):
    if ranges and pc==ranges[-1][1]+4:ranges[-1]=(ranges[-1][0],pc)
    else:ranges.append((pc,pc))
  regions.append(ranges)
  for lo,hi in ranges:
   seg=next(s for s in elf.iter_segments() if s['p_type']=='PT_LOAD' and s['p_vaddr']<=lo and hi+4<=s['p_vaddr']+s['p_filesz'])
   for pc in range(lo,hi+1,4):
    off=pc-seg['p_vaddr']+seg['p_offset'];ins=struct.unpack_from('<I',blob,off)[0];dis=list(md.disasm(blob[off:off+4],pc));assert len(dis)==1,hex(pc)
    assert ins>>28!=15 and (ins>>25)&7 not in [6,7],(hex(pc),dis[0].mnemonic)
    if (ins>>25)&7==5:assert not ins&(1<<24),'Calls cannot be accelerated'
    else:
     assert not (((ins>>25)&7)==4 and (ins&(1<<20)) and (ins&(1<<15))), 'LDM to PC must remain interpreted'
     assert not ('pc' in dis[0].op_str.split(',')[0]),(hex(pc),dis[0].mnemonic)
    ops[pc]=ins
 out=['// Generated by tools/generate_arm_hot.py; HL4 opcodes, specialized local decoder.',
 'static constexpr unsigned regionCount='+str(len(regions))+';',
 'static u32 entry(unsigned i){static constexpr u32 a[]={'+','.join(hex(r[0][0]+0x02000000) for r in regions)+'};return a[i];}',
 'bool guard(unsigned i){switch(i){']
 for i,ranges in enumerate(regions):
  out+=['case '+str(i)+':{static constexpr u32 expected[][2]={'+','.join('{0x%x,0x%xu}'%(pc+0x02000000,ops[pc]) for lo,hi in ranges for pc in range(lo,hi+1,4))+'};for(const auto& p:expected)if(load32(p[0])!=p[1])return false;return true;}']
 out+=['default:return false;}}','void run(unsigned i){switch(i){']
 for i,ranges in enumerate(regions):out+=['case '+str(i)+':return runRegion'+str(i)+'();']
 out+=['default:throw std::runtime_error("Unknown hot region");}}']
 for i,ranges in enumerate(regions):
  included={pc for lo,hi in ranges for pc in range(lo,hi+1,4)}
  leaders={ranges[0][0]}
  for pc in included:
   if (ops[pc]>>25)&7==5:leaders.update([branch_target(pc,ops[pc]),pc+4])
   if emit(pc+0x02000000,ops[pc]).startswith('step<'):leaders.update([pc,pc+4])
  if i in WHOLE:
   # Bound compiler optimization graphs. Native page transitions stay inside
   # HotArm, without expensive Unicorn register synchronization per scanline.
   pages={}
   for pc in sorted(included):pages.setdefault((pc+0x02000000)>>10,[]).append(pc)
   out+=['void runRegion'+str(i)+'(){for(;;){switch(r[15]>>10){']
   for page in pages:out+=['case 0x%x:if(!page%d_%x())return;break;'%(page,i,page)]
   out+=['default:return;}}}']
   groups=list(pages.items())
  else:groups=[(None,sorted(included))]
  for page,pcs in groups:
   local=set(pcs)
   # Charge direct instructions once per straight-line block. Branches and
   # decoder fallbacks count themselves. No register-shift may observe the
   # virtual PC: PC-relative operands are emitted from their original address.
   charged=set();charges={}
   for start in pcs:
    if start in charged or (ops[start]>>25)&7==5 or emit(start+0x02000000,ops[start]).startswith('step<'):continue
    q=start;n=0
    while q in local and (q==start or q not in leaders) and (ops[q]>>25)&7!=5 and not emit(q+0x02000000,ops[q]).startswith('step<'):
     charged.add(q);n+=1;q+=4
    charges[start]=n
   if page is None:out+=['void runRegion'+str(i)+'(){']
   else:
    out+=['HL4_HOT_NOINLINE bool page%d_%x(){switch(r[15]){'%(i,page)]
    out+=['case 0x%x:goto L%x;'%(pc+0x02000000,pc) for pc in pcs]
    out+=['default:return false;}']
   def dest(pc):
    if pc in local:return 'goto L%x;'%pc
    return 'r[15]=0x%x;return%s;'%(pc+0x02000000,(' true' if pc in included else ' false') if page is not None else '')
   for pc in pcs:
    ins=ops[pc];out+=['L%x:'%pc]
    if pc in charges:out+=['icount+='+str(charges[pc])+';']
    if (ins>>25)&7==5:
     off=(ins&0xffffff)*4
     if off&(1<<25):off-=1<<26
     target=pc+8+off;cc=ins>>28
     code='++icount;'
     if target<=pc:code+='if(icount>100000000)throw std::runtime_error("Hot ARM instruction budget");'
     code+=('if(cond(%d)){'%cc+dest(target)+'}') if cc!=14 else dest(target)
     if cc!=14:code+=dest(pc+4)
     out+=[code]
    else:
     instruction=emit(pc+0x02000000,ins,update_pc=False,count=False)
     if instruction.startswith('step<'):out+=['r[15]=0x%x;'%(pc+0x02000000)]
     out+=[instruction,dest(pc+4)]
   out+=['}']
 return '\n'.join(out)+'\n'
if __name__=='__main__':
 p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');a=p.parse_args();out=generate();path=ROOT/'src/arm_hot_blocks.inc'
 if a.check:assert path.read_text(encoding='utf8')==out,'Stale generated ARM blocks'
 else:path.write_text(out,encoding='utf8')
 print('PASS',len(REGIONS),'HL4 generated/guarded regions')
